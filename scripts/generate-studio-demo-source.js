import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const projectDir = path.join(rootDir, "examples", "studio-demo");
const outputFile = path.join(rootDir, "src", "studio-demo-source.generated.js");
const textExtensions = new Set([".md", ".yml", ".yaml", ".svg", ".txt", ".json"]);

function collectFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) return collectFiles(absolute);
    const relative = path.relative(projectDir, absolute).replaceAll(path.sep, "/");
    const extension = path.extname(entry.name).toLowerCase();
    const value = textExtensions.has(extension)
      ? { type: "text", value: fs.readFileSync(absolute, "utf8") }
      : { type: "binary", value: fs.readFileSync(absolute).toString("base64") };
    return [[relative, value]];
  });
}

function renderSource() {
  const files = Object.fromEntries(collectFiles(projectDir).sort(([a], [b]) => a.localeCompare(b)));
  const entries = Object.entries(files).map(([filePath, file]) => {
    const value = file.type === "text"
      ? JSON.stringify(file.value)
      : `decodeBase64(${JSON.stringify(file.value)})`;
    return `  ${JSON.stringify(filePath)}: ${value}`;
  }).join(",\n");
  return [
    "// Generated from examples/studio-demo by scripts/generate-studio-demo-source.js.",
    "// Do not edit this file directly; edit the YAML/Markdown project and regenerate.",
    "function decodeBase64(value) {",
    "  const binary = globalThis.atob(value);",
    "  return Uint8Array.from(binary, (char) => char.charCodeAt(0));",
    "}",
    `export const studioDemoFiles = Object.freeze({\n${entries}\n});`,
    ""
  ].join("\n");
}

const expected = renderSource();
if (process.argv.includes("--check")) {
  const actual = fs.existsSync(outputFile) ? fs.readFileSync(outputFile, "utf8") : "";
  if (actual !== expected) {
    console.error("Studio Demo source is stale. Run: npm run demo:generate");
    process.exit(1);
  }
} else {
  fs.writeFileSync(outputFile, expected);
  console.log(`Generated: ${path.relative(rootDir, outputFile)}`);
}
